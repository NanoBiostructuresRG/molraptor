"""Result writing utilities for MOLRAPTOR.

This module provides :class:`ResultManager`, which writes pipeline outputs
to disk as a human-readable TXT report. The report is produced by the main
pipeline after all steps have been executed.
"""

from __future__ import annotations

import os
from datetime import datetime
from pathlib import Path

import numpy as np
import pandas as pd

from .version import PROJECT_LICENSE, PROJECT_NAME, __version__

__all__ = ["ResultManager"]


class ResultManager:
    """Write pipeline results to a TXT file.

    Parameters
    ----------
    output_file : str or pathlib.Path
        Full path to the TXT results file. The parent directory is created
        automatically if it does not exist.

    Examples
    --------
    >>> rm = ResultManager("artifacts/summary.txt")
    >>> rm.write_results(curated_df, fingerprints)
    """

    def __init__(self, output_file: str | Path) -> None:
        self.output_file = output_file
        output_dir = os.path.dirname(self.output_file)
        if output_dir:
            os.makedirs(output_dir, exist_ok=True)

    def _get_header(self) -> str:
        return f"""
=====================================================
                     {PROJECT_NAME}
   Modular pipeline for fetching, curating, and
        encoding molecular data and fingerprints
-----------------------------------------------------
CLI: molraptor run
Package: molraptor
Version: {__version__}
Licence: {PROJECT_LICENSE}
Execution Date: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}
-----------------------------------------------------
Repository: https://github.com/NanoBiostructuresRG/molraptor
=====================================================

"""

    def _get_statistics(self, df: pd.DataFrame, fingerprints: np.ndarray) -> str:
        """Generate dataset and fingerprint statistics block."""
        total = len(df)
        valid_smiles = df["SMILES"].notna().sum() if "SMILES" in df.columns else "N/A"
        n_pos = (df["Label"] == 1).sum() if "Label" in df.columns else "N/A"
        n_neg = (df["Label"] == 0).sum() if "Label" in df.columns else "N/A"
        pct_pos = f"{(n_pos / total) * 100:.1f}%" if isinstance(n_pos, (int, float)) else "N/A"
        pct_neg = f"{(n_neg / total) * 100:.1f}%" if isinstance(n_neg, (int, float)) else "N/A"
        fp_count = len(fingerprints)
        fp_dim = fingerprints.shape[1] if fingerprints.ndim == 2 else "N/A"

        return f"""Dataset Summary:
  Total entries:          {total}
  Valid SMILES:           {valid_smiles}
  Class 0 (inactive):     {n_neg} ({pct_neg})
  Class 1 (active):       {n_pos} ({pct_pos})

Fingerprint Summary:
  Generated:              {fp_count}
  Dimension (bits):       {fp_dim}
"""

    def write_results(self, df: pd.DataFrame, fingerprints: np.ndarray) -> None:
        """Write a human-readable TXT report to disk.

        Parameters
        ----------
        df : pandas.DataFrame
            Curated dataset after curation step.
        fingerprints : numpy.ndarray
            Fingerprint matrix generated by the fingerprint step.

        Notes
        -----
        The header includes the current ``__version__`` string from
        :mod:`molraptor.version`, so the report always reflects the version
        that generated it.
        """
        content = self._get_statistics(df, fingerprints)
        try:
            with open(self.output_file, "w", encoding="utf-8") as f:
                f.write(self._get_header())
                f.write(content)
        except Exception as e:
            raise IOError(f"Error writing results to '{self.output_file}': {e}")